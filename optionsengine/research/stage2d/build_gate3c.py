def build(root: str, out: str) -> dict:
    if "stage2d" not in os.path.normpath(out).split(os.sep):
        raise ValueError("Stage 2D outputs must live under a 'stage2d' directory")
    os.makedirs(out, exist_ok=True)
    s = K.Src(root)
    claims = K.build_claims(s)
    t1s, t1r = K.tier1_checks(s, True), K.tier1_checks(s, False)
    bad = L.check_ledger(claims, {**t1s})
    if bad:
        raise ValueError("claim ledger violates its own rules: " + "; ".join(bad))
    df = ledger_frame(claims, t1s, t1r)
    df.to_csv(os.path.join(out, "claim_ledger.csv"), index=False)
    with open(os.path.join(out, "claim_ledger.md"), "w", encoding="utf-8") as f:
        f.write(ledger_markdown(df))
    # report (lint counts need a first pass over the generated text)
    old = [os.path.join(root, p) for p in REPORTS if os.path.exists(os.path.join(root, p))]
    old = [p for p in old if not p.endswith(("GATE3C_IMPLEMENTATION_PLAN.md", PROTOCOL))] if False else old
    rep = final_report(df, s, dict(new_flags=0, old_flags=0, old_ok=0))
    findings = []
    findings += L.lint_text(rep, "FINAL_REPORT.md")
    findings += L.lint_text(ledger_markdown(df), "claim_ledger.md")
    findings += L.lint_files(old)
    new = [f for f in findings if f["source"] in ("FINAL_REPORT.md", "claim_ledger.md") or f["source"].endswith((PROTOCOL, "GATE3C_IMPLEMENTATION_PLAN.md"))]
    oldf = [f for f in findings if f not in new]
    counts = dict(new_flags=sum(f["status"] == "FLAG" for f in new), old_flags=sum(f["status"] == "FLAG" for f in oldf), old_ok=sum(f["status"] == "NEGATED_OK" for f in oldf))
    rep = final_report(df, s, counts)
    with open(os.path.join(out, "FINAL_REPORT.md"), "w", encoding="utf-8") as f:
        f.write(rep)
    pd.DataFrame(findings).to_csv(os.path.join(out, "lint_report.csv"), index=False)
    meta = dict(git_commit=_git(), n_claims=len(df), statuses=df.status.value_counts().to_dict(), lint=counts, protocol_sha256=sha(os.path.join(out, PROTOCOL)) if os.path.exists(os.path.join(out, PROTOCOL)) else None,
                source_hashes={p: sha(p) for p in sorted(glob.glob(os.path.join(root, "gate*", "*.csv")))}, generated=datetime.now().isoformat(timespec="seconds"), plan="GATE3C_IMPLEMENTATION_PLAN.md")
    with open(os.path.join(out, "run_metadata_3c.json"), "w") as f:
        json.dump(meta, f, indent=1)
    return meta


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="research_output/stage2d")
    ap.add_argument("--out", default="research_output/stage2d/gate3")
    a = ap.parse_args(argv)
    m = build(a.root, a.out)
    print(json.dumps({k: v for k, v in m.items() if k != "source_hashes"}, indent=1))


if __name__ == "__main__":
    main()
