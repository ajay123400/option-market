def sha(path: str) -> str:
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def _git() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def ledger_frame(claims: List[K.Claim], tier1_s, tier1_r) -> pd.DataFrame:
    rows = []
    for c in claims:
        chk = tier1_s if "S1" in c.estimands and c.claim_id == "C01" else tier1_r if c.claim_id == "C03" else None
        rows.append(dict(claim_id=c.claim_id, topic=c.topic, status=c.status, evidence_tier=c.tier, tier_meaning=K.TIERS[c.tier], claim=c.claim, key_numbers=c.key_numbers, sources=c.sources, required_warnings=c.warnings,
                         allowed_wording=c.allowed, forbidden_wording=c.forbidden, estimands=";".join(c.estimands), interval_based=c.interval_based, t11_undercoverage_warning_attached=c.undercoverage_warning,
                         tier1_conditions=("" if chk is None else ";".join(f"{k}={v}" for k, v in chk.items()))))
    return pd.DataFrame(rows)


def ledger_markdown(df: pd.DataFrame) -> str:
    out = ["# Stage 2D claim ledger", "", "Generated by `build_gate3c.py` from the committed Gate 1-3b CSVs; every number is read from those files. Status vocabulary and tiers: see `FINAL_REPORT.md`.", ""]
    for _, r in df.iterrows():
        out += [f"## {r.claim_id} — {r.topic}", f"**Status:** {r.status} · **Evidence tier:** {r.evidence_tier} ({r.tier_meaning})", "", f"**Claim.** {r.claim}", "", f"**Numbers.** {r.key_numbers}", "",
                f"**Required warnings.** {r.required_warnings}", "", f"**Allowed wording.** {r.allowed_wording}", "", f"**Forbidden wording.** {r.forbidden_wording}", "", f"**Sources.** {r.sources}", ""]
        if r.tier1_conditions:
            out += [f"**Tier 1 conditions checked.** {r.tier1_conditions}", ""]
    return "\n".join(out) + "\n"


